//! Lifecycle metadata that generated documentation must not roll back.

use std::collections::{BTreeMap, BTreeSet};
use std::io;
use std::rc::Rc;

use raf_okf::{DocType, Document, ErrorTag, Profile, RafDocument, State};
use raf_source::{EntryKind, RelPath, Tree as _};

use crate::load::{READ_LIMIT, is_markdown, is_navigation_index};
use crate::publication_io::Root;
use crate::{SyncError, Workplan, finding::kind};

use super::refused;

const DIRECTORIES: [DocType; 2] = [DocType::Capability, DocType::Change];

#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) enum Metadata {
    Capability(State),
    Change(BTreeSet<String>),
}

impl Metadata {
    pub(super) fn of(document: &RafDocument) -> Option<Self> {
        match document {
            RafDocument::Capability(capability) => Some(Self::Capability(capability.state)),
            RafDocument::Change(change) => {
                Some(Self::Change(change.changes.iter().cloned().collect()))
            }
            _ => None,
        }
    }
}

/// The state and ownership projection of the loaded documents. Authored prose,
/// assessment inputs, and generated bytes do not participate in the comparison.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct Basis(BTreeMap<String, Metadata>);

impl Basis {
    pub(super) fn of(plan: &Workplan<'_>) -> Result<Self, SyncError> {
        let misplaced: Vec<_> = plan
            .findings
            .iter()
            .filter(|finding| {
                finding.kind == kind::WRONG_DIRECTORY
                    && finding.file.rsplit_once('/').is_some_and(|(parent, _)| {
                        DIRECTORIES
                            .iter()
                            .any(|doc_type| parent == doc_type.directory())
                    })
            })
            .cloned()
            .collect();
        if !misplaced.is_empty() {
            return Err(SyncError::Refused(misplaced));
        }
        Ok(Self(
            plan.capabilities()
                .iter()
                .map(|capability| {
                    (
                        capability.path().to_owned(),
                        Metadata::Capability(capability.value().state),
                    )
                })
                .chain(plan.changes().iter().map(|change| {
                    (
                        change.path().to_owned(),
                        Metadata::Change(change.value().changes.iter().cloned().collect()),
                    )
                }))
                .collect(),
        ))
    }

    pub(super) fn verify(&self, root: &Rc<Root>) -> io::Result<()> {
        if *self != Self::read(root)? {
            return Err(io::Error::other(
                "a capability state or change ownership changed; compute a fresh docs sync report",
            ));
        }
        Ok(())
    }

    fn read(root: &Rc<Root>) -> io::Result<Self> {
        let mut documents = BTreeMap::new();
        let tree = root.tree();
        for doc_type in DIRECTORIES {
            let directory = RelPath::new(doc_type.directory()).map_err(io::Error::other)?;
            match root.directory(&directory) {
                Ok(_) => {}
                Err(error) if error.kind() == io::ErrorKind::NotFound => continue,
                Err(error) => return Err(error),
            }
            let entries = tree
                .list(&directory)
                .map_err(|error| refused(&directory, &error.to_string()))?;
            for entry in entries {
                if entry.kind == EntryKind::Dir
                    || is_navigation_index(&entry.name)
                    || !is_markdown(&entry.name)
                {
                    continue;
                }
                let path = directory.join(&entry.name).map_err(io::Error::other)?;
                let text = tree
                    .read(&path, READ_LIMIT)
                    .map_err(|error| refused(&path, &error.to_string()))?;
                let document = match Document::parse(&text) {
                    Ok(document) => document,
                    // The Workplan loader treats pages without frontmatter as
                    // stray Markdown, so they hold no lifecycle metadata.
                    Err(error) if error.kind().tag() == ErrorTag::MissingFence => continue,
                    Err(error) => return Err(refused(&path, &error.to_string())),
                };
                if document.doc_type() != Some(doc_type) {
                    return Err(refused(
                        &path,
                        "unexpected document type in a lifecycle directory; move it to its declared directory",
                    ));
                }
                let metadata = Metadata::of(&typed(&path, &document)?)
                    .ok_or_else(|| refused(&path, "missing lifecycle metadata"))?;
                documents.insert(path.as_str().to_owned(), metadata);
            }
        }
        Ok(Self(documents))
    }
}

pub(super) fn typed(path: &RelPath, document: &Document) -> io::Result<RafDocument> {
    Profile
        .validate(document, path.as_str())
        .map_err(|_| refused(path, "destination text is not an owned typed document"))
}
